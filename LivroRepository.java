package repository;

import connection.ConnectionFactory;
import entity.Livro;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * All communication with the "livro" table lives here (CRUD).
 * Every method opens its own connection through ConnectionFactory and closes it
 * automatically with try-with-resources. SQLException is propagated to the caller,
 * which decides how to report it to the user.
 */
public class LivroRepository {

    private static final String INSERT =
            "INSERT INTO livro (titulo, autor, ano_publicacao, disponivel) VALUES (?, ?, ?, ?)";

    private static final String SELECT_ALL =
            "SELECT id, titulo, autor, ano_publicacao, disponivel FROM livro ORDER BY id";

    private static final String SELECT_BY_ID =
            "SELECT id, titulo, autor, ano_publicacao, disponivel FROM livro WHERE id = ?";

    private static final String UPDATE =
            "UPDATE livro SET titulo = ?, autor = ?, ano_publicacao = ?, disponivel = ? WHERE id = ?";

    private static final String DELETE =
            "DELETE FROM livro WHERE id = ?";

    /** Inserts a book and stores the id generated by the database in the given object. */
    public void insert(Livro livro) throws SQLException {
        try (Connection connection = ConnectionFactory.getConnection();
             // The second argument asks the driver to return the generated "id" column.
             PreparedStatement statement = connection.prepareStatement(INSERT, new String[] {"id"})) {

            statement.setString(1, livro.getTitulo());
            statement.setString(2, livro.getAutor());
            statement.setInt(3, livro.getAnoPublicacao());
            statement.setBoolean(4, livro.isDisponivel());

            statement.executeUpdate();

            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (keys.next()) {
                    livro.setId(keys.getInt(1));
                }
            }
        }
    }

    /** Returns every book, ordered by id. */
    public List<Livro> findAll() throws SQLException {
        List<Livro> livros = new ArrayList<>();

        try (Connection connection = ConnectionFactory.getConnection();
             PreparedStatement statement = connection.prepareStatement(SELECT_ALL);
             ResultSet rs = statement.executeQuery()) {

            while (rs.next()) {
                livros.add(mapRow(rs));
            }
        }
        return livros;
    }

    /** Returns the book with the given id, or an empty Optional if it does not exist. */
    public Optional<Livro> findById(int id) throws SQLException {
        try (Connection connection = ConnectionFactory.getConnection();
             PreparedStatement statement = connection.prepareStatement(SELECT_BY_ID)) {

            statement.setInt(1, id);

            try (ResultSet rs = statement.executeQuery()) {
                if (rs.next()) {
                    return Optional.of(mapRow(rs));
                }
            }
        }
        return Optional.empty();
    }

    /** Updates all editable fields of a book. Returns true if a row was changed. */
    public boolean update(Livro livro) throws SQLException {
        try (Connection connection = ConnectionFactory.getConnection();
             PreparedStatement statement = connection.prepareStatement(UPDATE)) {

            statement.setString(1, livro.getTitulo());
            statement.setString(2, livro.getAutor());
            statement.setInt(3, livro.getAnoPublicacao());
            statement.setBoolean(4, livro.isDisponivel());
            statement.setInt(5, livro.getId());

            int linhasAfetadas = statement.executeUpdate();
            return linhasAfetadas > 0;
        }
    }

    /** Deletes a book by id. Returns true if a row was removed. */
    public boolean delete(int id) throws SQLException {
        try (Connection connection = ConnectionFactory.getConnection();
             PreparedStatement statement = connection.prepareStatement(DELETE)) {

            statement.setInt(1, id);

            int linhasAfetadas = statement.executeUpdate();
            return linhasAfetadas > 0;
        }
    }

    // Converts the current row of the ResultSet into a Livro object, field by field.
    private Livro mapRow(ResultSet rs) throws SQLException {
        Livro livro = new Livro();
        livro.setId(rs.getInt("id"));
        livro.setTitulo(rs.getString("titulo"));
        livro.setAutor(rs.getString("autor"));
        livro.setAnoPublicacao(rs.getInt("ano_publicacao"));
        livro.setDisponivel(rs.getBoolean("disponivel"));
        return livro;
    }
}
